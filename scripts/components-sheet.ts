// Fills docs/components.html's <style id="tailwind"> with the app's own CSS:
// Tailwind and src/styles/theme/, built for just the classes the sheet uses.
//
//   bun run components:sheet
//
// The markup is hand-written; this only refreshes its styles, so edit the
// sheet, run this, open the file in a browser. Fonts come from Google there:
// @fontsource's @font-face rules point at files beside node_modules, so they
// are dropped here.

import { compile } from "@tailwindcss/node";
import { Scanner } from "@tailwindcss/oxide";

const SHEET = new URL("../docs/components.html", import.meta.url);
const html = await Bun.file(SHEET).text();

const compiler = await compile(`@import "tailwindcss";\n@import "../src/styles/theme/index.css";`, {
  base: new URL("../docs/", import.meta.url).pathname,
  onDependency() {},
});
const candidates = new Scanner({}).scanFiles([{ content: html, extension: "html" }]);
const css = compiler
  .build(candidates)
  .replace(/@font-face\s*\{[^}]*\}/g, "")
  .replaceAll("</style", "<\\/style");

const STYLE = /^<style id="tailwind">[\s\S]*?<\/style>/m;
if (!STYLE.test(html)) throw new Error('docs/components.html has no <style id="tailwind"> block');
await Bun.write(
  SHEET,
  html.replace(STYLE, () => `<style id="tailwind">/* generated by scripts/components-sheet.ts */\n${css}</style>`)
);
console.log(`docs/components.html: ${candidates.length} candidates, ${Math.round(css.length / 1024)} KB of CSS`);
